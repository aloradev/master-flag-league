      await page.getByText('No hay avisos nuevos.', { exact: true }).waitFor();
      await page.goto(`${base}/partido/demo_final`);
      await page.waitForFunction(() => document.title.includes('18 - 6'));
      assert.ok((await page.title()).includes(`${game.home_team_name} 18 - 6 ${game.away_team_name}`));
      assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), 'https://master-flag-league.vercel.app/partido/demo_final');
