      await page.getByRole('checkbox', { name: 'Avisos en esta web' }).uncheck();
      const count = await page.evaluate(key => JSON.parse(localStorage.getItem(key)).notices.length, key);
      game = { ...game, status: 'POSTPONED' };
      await page.reload();
      assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).notices.length, key), count);
      await page.getByRole('checkbox', { name: 'Avisos en esta web' }).check();
      await page.waitForFunction(key => Object.keys(JSON.parse(localStorage.getItem(key)).snapshots).length > 0, key);
      assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).notices.length, key), count);
