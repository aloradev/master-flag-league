import assert from 'node:assert/strict';
import pool from '../dist/config/database.js';
import { resetFinance } from '../dist/controllers/finance.controller.js';
let calls=[];
let found=true;
let fail=false;
pool.connect=async()=>({query:async(sql,params)=>{
  calls.push({sql,params});
  if(sql.startsWith('SELECT id FROM seasons')) return {rows:found?[{id:'season'}]:[]};
  if(sql.startsWith('INSERT INTO audit_logs') && fail) throw new Error('audit failed');
  return {rows:sql.startsWith('DELETE')?[{id:'entry'}]:[]};
},release(){}});
const invoke=(body={},role='FINANCE_ADMIN')=>new Promise(resolve=>resetFinance({body:{seasonId:'season',confirmation:'REINICIAR',...body},user:{id:'user',leagueId:'league',role}}, {json:data=>resolve({data})},error=>resolve({error})));
let r=await invoke();
assert.deepEqual(r.data.data,{fees:1,payments:1,expenses:1});
assert.ok(calls.some(c=>c.sql==='COMMIT'));
assert.deepEqual(calls.find(c=>c.sql.startsWith('SELECT')).params,['season','league']);
for(const c of calls.filter(c=>c.sql.startsWith('DELETE'))) assert.deepEqual(c.params,['season']);
assert.equal((await invoke({},'TEAM_MANAGER')).error.statusCode,403);
assert.equal((await invoke({confirmation:'yes'})).error.statusCode,400);
assert.equal((await invoke({seasonId:null})).error.statusCode,400);
found=false; calls=[];
assert.equal((await invoke()).error.statusCode,404);
assert.ok(!calls.some(c=>c.sql.startsWith('DELETE')));
assert.ok(calls.some(c=>c.sql==='ROLLBACK'));
found=true; fail=true; calls=[];
assert.ok((await invoke()).error);
assert.ok(calls.some(c=>c.sql==='ROLLBACK'));
assert.ok(!calls.some(c=>c.sql==='COMMIT'));
console.log('OK: permisos, confirmación, alcance por liga/temporada y rollback si falla auditoría.');
await pool.end();
